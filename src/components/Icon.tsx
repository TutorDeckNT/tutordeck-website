export default function Icon({ className = '' }: { className?: string }) {
  const tokens = className.split(/\s+/);
  if (tokens.includes('fa-instagram')) return <span aria-hidden="true" className={`td-icon ${tokens.filter(token => !token.startsWith('fa') && token !== 'fab').join(' ')}`}><svg width="1em" height="1em" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" focusable="false"><rect x="3" y="3" width="18" height="18" rx="5" /><circle cx="12" cy="12" r="4" /><circle cx="17.5" cy="6.5" r=".5" fill="currentColor" /></svg></span>;
  const name = tokens.find(token => token in icons);
  const Graphic = name ? icons[name] : CircleAlert;
  const classes = tokens.filter(token => !token.startsWith('fa-') && token !== 'fas' && token !== 'fab').join(' ');
  return <span aria-hidden="true" className={`td-icon ${classes} ${tokens.includes('fa-spin') ? 'animate-spin' : ''}`}><Graphic width="1em" height="1em" strokeWidth={2} focusable="false" aria-hidden="true" /></span>;
}
